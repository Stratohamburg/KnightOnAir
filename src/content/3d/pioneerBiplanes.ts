import { PioneerAssembly, sides, wingId, type Point3, type Rib, linen, iron } from "./pioneerAssembly";

const body = "center_body",
  tail = "tail",
  engine = "engine_0";
type BoomStation = [z: number, halfWidth: number, upper: number, lower: number];
function booms(a: PioneerAssembly, stations: BoomStation[], radius = 0.041) {
  for (const s of sides) {
    let previous: [Point3, Point3] | undefined;
    for (const [z, x, upper, lower] of stations) {
      const top: Point3 = [s * x, upper, z],
        bottom: Point3 = [s * x, lower, z];
      a.rod(tail, top, bottom, radius * 0.7);
      if (previous) {
        a.rod(tail, previous[0], top, radius);
        a.rod(tail, previous[1], bottom, radius);
        a.wire(tail, previous[0], bottom);
        a.wire(tail, previous[1], top);
        a.wire(tail, previous[1], [-bottom[0], bottom[1], bottom[2]]);
      }
      if (s === 1) a.rod(tail, bottom, [-x, lower, z], radius * 0.68);
      previous = [top, bottom];
    }
  }
}
function pusherEngine(a: PioneerAssembly, z: number, y: number, r: number) {
  a.box(engine, [0, y - 0.07, z + 0.37], [0.54, 0.39, 0.62], iron, "crankcase");
  for (const s of sides)
    for (const d of [0.19, 0.36, 0.53, 0.7]) {
      a.rod(engine, [s * 0.17, y + 0.04, z + d], [s * 0.32, y + 0.3, z + d], 0.087, iron, "cylinders");
    }
  a.prop(engine, [0, y, z], r);
}

